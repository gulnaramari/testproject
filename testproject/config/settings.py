# --- Безопасные функции для env ---
def env_bool(name: str, default: bool = False) -> bool:
    return os.getenv(name, str(default)).strip().lower() in ("1", "true", "yes", "on")

def env_str(name: str, default: str = "") -> str:
    return os.getenv(name, default)

